#!/bin/bash
#
# Build scripts/vendor.js: the runtime libraries, compiled into one classic
# script that the page can load before public/scripts.js.
#
# The libraries are taken from node_modules, so this runs wherever npm install
# has been run (a development machine), and needs Node.js only for the final
# syntax check.
#
# Why a separate file: tsyringe is published as CommonJS for Node and as ES
# modules for bundlers. A browser loading a classic script cannot use either
# directly, and a TypeScript compiler alone cannot turn one into the other. So
# tsyringe's ES5 module build is concatenated here, once, and shipped as a
# normal script. Its ES5 form is deliberate: it emits "var Foo = (function
# (_super) { ... }(Bar))" rather than "class Foo extends Bar", and a function
# call is evaluated in order, so modules with circular imports (tsyringe's
# Registry <-> DependencyContainer) initialise correctly however the bundler
# orders them. Native class declarations would hit the temporal dead zone.
#
#   <script src="/vendor.js"></script>
#   <script src="/scripts.js"></script>
#
# Deployments do not rebuild this: deploy.sh compiles only src/, and vendor.js
# changes only when the libraries are upgraded.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT}"

OUTPUT="public/vendor.js"
TSYRINGE_DIR="node_modules/tsyringe/dist/esm5"
REFLECT_SOURCE="node_modules/reflect-metadata/Reflect.js"
STAGE="$(mktemp -d)"
trap 'rm -rf "${STAGE}"' EXIT

if [ ! -d "${TSYRINGE_DIR}" ]; then
    echo "x tsyringe is not installed. Run npm install first." >&2
    exit 1
fi
if [ ! -f "${REFLECT_SOURCE}" ]; then
    echo "x reflect-metadata is not installed. Run npm install first." >&2
    exit 1
fi

# The bundle script works on a directory tree, so lay the libraries out in the
# order they must load: the polyfill first, then tsyringe's own modules.
mkdir -p "${STAGE}/lib"
rsync -a "${TSYRINGE_DIR}/" "${STAGE}/lib/"
# tslib helpers (__awaiter, __decorate, ...) are imported by the ESM build;
# copy its version rather than inlining tslib's Node-specific glue.
if [ -f node_modules/tslib/tslib.es6.js ]; then
    cp node_modules/tslib/tslib.es6.js "${STAGE}/lib/tslib.js"
fi

# reflect-metadata's UMD wrapper defines Reflect.apply and friends if they are
# missing, then defines the Reflect.decorate/metadata API. It is not an ES
# module, so it is prepended as-is; running inside the same IIFE is harmless
# because it assigns to the global Reflect object.
{
    echo '/* Generated by scripts/build-vendor.sh - do not edit directly. */'
    echo '(function () {'
    echo '"use strict";'
    echo '// ---------- reflect-metadata ----------'
    cat "${REFLECT_SOURCE}"
    echo
    echo '// ---------- tsyringe ----------'
} > "${STAGE}/head.js"

# tsyringe modules, dependency-ordered by the shared bundler.
node "${ROOT}/scripts/bundle.mjs" "${STAGE}/lib" "index.js" "${STAGE}/tsyringe.js"

# Splice the two together, dropping the bundler's own prologue and epilogue.
#
# The bundle is an IIFE, so the library's names live in its own scope. The
# app's script is a separate classic script with its own scope, and the
# bundler strips its imports, leaving bare references ("injectable()") that
# resolve to nothing unless the library publishes them. So the public API is
# copied onto the global object on the way out: same names, same objects.
{
    cat "${STAGE}/head.js"
    sed -e '1,3d' -e '$d' "${STAGE}/tsyringe.js"
    cat <<'GLOBALS'
// ---------- globals ----------
// The app script is bundled separately, so it needs these on the global
// object rather than in this IIFE's scope.
Object.assign(globalThis, {
    container,
    injectable,
    inject,
    singleton,
    autoInjectable,
    injectAll,
    injectWithTransform,
    injectAllWithTransform,
    registry,
    scoped,
    delay,
    Lifecycle
});
}());
GLOBALS
} > "${OUTPUT}"

if command -v node >/dev/null 2>&1; then
    node --check "${OUTPUT}"
fi

echo "✓ Built ${OUTPUT} ($(wc -c < "${OUTPUT}") bytes)"
